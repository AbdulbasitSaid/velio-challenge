// Generates the web theme (Tailwind 4 @theme) and the Dart tokens from tokens.json, the one source.
// Outputs are committed; CI regenerates them and fails on any diff. The Dart file is not run through
// `dart format`, so CI needs no Dart SDK to check it.
import tokens from './tokens.json';

type Token = { name: string; value: string };
type TextStyle = {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing?: string;
};

const root = import.meta.dir;
const header = 'Generated by packages/design-tokens/build.ts from tokens.json. Do not edit.';
const px = (v: string) => Number(v.replace('px', ''));
const strip = (name: string, prefix: string) => name.replace(new RegExp(`^${prefix}-`), '');
const camel = (name: string) => name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

const colors: Token[] = tokens.color.tokens;
const styles: (TextStyle & { family: string })[] = tokens.type.groups.flatMap((g) =>
  g.styles.map((s) => ({ ...s, family: g.family })),
);
const spacing: Token[] = tokens.spacing.tokens;
const radius: Token[] = tokens.radius.tokens;
const shadows: Token[] = tokens.shadow.tokens;
const sizes: Record<string, string> = Object.fromEntries(tokens.size.tokens.map((t) => [t.name, t.value]));

// ---- CSS ----

const css = [
  `/* ${header} */`,
  '@theme {',
  ...colors.map((c) => `  --color-${c.name}: ${c.value};`),
  `  --font-display: ${tokens.type.families.display};`,
  `  --font-body: ${tokens.type.families.body};`,
  ...styles.flatMap((s) => [
    `  --text-${s.name}: ${s.fontSize};`,
    `  --text-${s.name}--line-height: ${s.lineHeight};`,
    `  --text-${s.name}--font-weight: ${s.fontWeight};`,
    ...(s.letterSpacing ? [`  --text-${s.name}--letter-spacing: ${s.letterSpacing};`] : []),
  ]),
  ...radius.map((r) => `  --radius-${strip(r.name, 'radius')}: ${r.value};`),
  ...shadows.map((s) => `  --shadow-${strip(s.name, 'shadow')}: ${s.value};`),
  `  --spacing-touch: ${sizes['touch-min']};`,
  `  --spacing-button: ${sizes['button-height']};`,
  `  --container-content: ${sizes['content-max']};`,
  '}',
  '',
  '/* Plain names, as the design system components use them (prototype tokens.css). */',
  ':root {',
  ...[...colors, ...spacing, ...radius, ...shadows, ...tokens.size.tokens].map(
    (t) => `  --${t.name}: ${t.value};`,
  ),
  '}',
  '',
].join('\n');

// ---- Dart ----

function dartColor(value: string): string {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) return `Color(0xFF${hex[1]!.toUpperCase()})`;
  const rgba = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(value);
  if (rgba) {
    const [r, g, b, a] = rgba.slice(1).map(Number) as [number, number, number, number];
    const h = (n: number) => n.toString(16).padStart(2, '0').toUpperCase();
    return `Color(0x${h(Math.round(a * 255))}${h(r)}${h(g)}${h(b)})`;
  }
  throw new Error(`Unsupported colour: ${value}`);
}

function dartShadows(value: string): string {
  const parts = value.split(/,(?![^(]*\))/).map((p) => p.trim());
  return parts
    .map((p) => {
      const m = /^(-?\d+)(?:px)? (-?\d+)(?:px)? (\d+)(?:px)? (rgba\([^)]+\))$/.exec(p);
      if (!m) throw new Error(`Unsupported shadow: ${p}`);
      return `BoxShadow(offset: Offset(${m[1]}, ${m[2]}), blurRadius: ${m[3]}, color: ${dartColor(m[4]!)})`;
    })
    .join(', ');
}

const familyName = (family: string) =>
  /^"([^"]+)"/.exec(tokens.type.families[family as 'display' | 'body'])![1]!;

const dart = [
  `// ${header}`,
  '// ignore_for_file: constant_identifier_names',
  '',
  "import 'package:flutter/painting.dart';",
  '',
  'abstract final class VelioColors {',
  ...colors.map((c) => `  static const ${camel(c.name)} = ${dartColor(c.value)};`),
  '',
  `  /// Avatar palette, in hash order.`,
  `  static const avatar = [lime, sky, sun, lilac, peach];`,
  '}',
  '',
  'abstract final class VelioFonts {',
  `  static const display = '${familyName('display')}';`,
  `  static const body = '${familyName('body')}';`,
  '}',
  '',
  'abstract final class VelioText {',
  ...styles.map((s) => {
    const fields = [
      `fontFamily: VelioFonts.${s.family}`,
      `fontSize: ${px(s.fontSize)}`,
      `height: ${+(px(s.lineHeight) / px(s.fontSize)).toFixed(4)}`,
      `fontWeight: FontWeight.w${s.fontWeight}`,
      ...(s.letterSpacing ? [`letterSpacing: ${px(s.letterSpacing)}`] : []),
    ];
    return `  static const ${camel(s.name)} = TextStyle(${fields.join(', ')});`;
  }),
  '}',
  '',
  'abstract final class VelioSpace {',
  ...spacing.map((s) => `  static const double s${strip(s.name, 'space')} = ${px(s.value)};`),
  '}',
  '',
  'abstract final class VelioRadius {',
  ...radius.map((r) => `  static const double ${camel(strip(r.name, 'radius'))} = ${px(r.value)};`),
  '}',
  '',
  'abstract final class VelioShadows {',
  ...shadows.map((s) => `  static const ${camel(strip(s.name, 'shadow'))} = [${dartShadows(s.value)}];`),
  '}',
  '',
  'abstract final class VelioSize {',
  ...Object.entries(sizes).map(([k, v]) => `  static const double ${camel(k)} = ${px(v)};`),
  '}',
  '',
  '/// Same function as packages/design-tokens/src/avatar.ts (djb2 over UTF-16 code units).',
  'int avatarIndex(String seed) {',
  '  var x = 5381;',
  '  for (final unit in seed.codeUnits) {',
  '    x = ((x << 5) + x + unit) & 0xFFFFFFFF;',
  '  }',
  '  return x % VelioColors.avatar.length;',
  '}',
  '',
].join('\n');

await Bun.write(`${root}/css/theme.css`, css);
await Bun.write(`${root}/dart/lib/velio_tokens.dart`, dart);
console.log('design tokens built');
